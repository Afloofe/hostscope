#![allow(clippy::expect_used)]

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

const VARIANTS: &[(&str, &str)] = &[
    ("variant-it-full", "it-full"),
    ("variant-ot-safe", "ot-safe"),
    ("variant-airgap", "airgap"),
    ("variant-observe-only", "observe-only"),
    ("variant-collector", "collector"),
];

const FEATURE_GATE_ENV: &str = "HEMOSTAT_FEATURE_GATE";
const FEATURE_GATE_VARIANT: &str = "feature-gate-check";

fn main() {

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=SOURCE_DATE_EPOCH");
    println!("cargo:rerun-if-env-changed=HEMOSTAT_SOURCE_REV");
    println!("cargo:rerun-if-env-changed={FEATURE_GATE_ENV}");
    println!("cargo:rerun-if-env-changed={SYSROOT_ID_ENV}");

    for p in git_watch_paths() {
        println!("cargo:rerun-if-changed={}", p.display());
    }

    let variant = resolve_variant();
    let toolchain = with_sysroot(rustc_version());
    let (source_rev, source_dirty) = source_revision();

    let source_date_epoch: u64 = env::var("SOURCE_DATE_EPOCH")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(0);

    let generated = format!(
        "// @generated by build.rs — do not edit.\n\
         pub(crate) const VARIANT: &str = {variant:?};\n\
         pub(crate) const TOOLCHAIN: &str = {toolchain:?};\n\
         pub(crate) const SOURCE_DATE_EPOCH: u64 = {source_date_epoch};\n\
         pub(crate) const SOURCE_REV: &str = {source_rev:?};\n\
         pub(crate) const SOURCE_DIRTY: bool = {source_dirty};\n"
    );

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is always set by Cargo"))
        .join("build_meta.rs");
    fs::write(&out, generated).expect("failed to write generated build metadata");
}

fn resolve_variant() -> String {
    let selected: Vec<&str> = VARIANTS
        .iter()
        .filter(|(feature, _)| cargo_feature_enabled(feature))
        .map(|(_, name)| *name)
        .collect();

    match selected.as_slice() {
        [one] => (*one).to_string(),
        [] if env::var(FEATURE_GATE_ENV).is_ok_and(|v| v == "1") => FEATURE_GATE_VARIANT.to_string(),
        [] => panic!(
            "no build variant selected.\n\n\
             Every HEMOSTAT image must name the variant it was built from, so that\n\
             its capability set is recorded in the build manifest and visible to an\n\
             operator and to a later examiner.\n\n\
             Choose one:\n{}\n\n\
             For example:\n    \
             cargo build --no-default-features --features variant-it-full\n",
            VARIANTS
                .iter()
                .map(|(f, n)| format!("    --features {f:<24} # {n}"))
                .collect::<Vec<_>>()
                .join("\n")
        ),
        many => panic!(
            "{} build variants selected at once: {}.\n\n\
             Exactly one variant must be named, or the build manifest cannot\n\
             describe the image. This usually means Cargo feature unification\n\
             pulled in a second variant through a dependency or a `--features`\n\
             list that was meant to be exclusive.\n",
            many.len(),
            many.join(", ")
        ),
    }
}

fn cargo_feature_enabled(feature: &str) -> bool {
    let key = format!("CARGO_FEATURE_{}", feature.to_uppercase().replace('-', "_"));
    env::var_os(key).is_some()
}

const SYSROOT_ID_ENV: &str = "HEMOSTAT_FREEBSD_SYSROOT_ID";

fn with_sysroot(rustc: String) -> String {
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("freebsd") {
        return rustc;
    }
    match env::var(SYSROOT_ID_ENV) {
        Ok(id) if !id.trim().is_empty() => format!("{rustc}; sysroot {}", id.trim()),
        _ => format!("{rustc}; sysroot UNPINNED"),
    }
}

fn rustc_version() -> String {
    let rustc = env::var_os("RUSTC").unwrap_or_else(|| "rustc".into());
    Command::new(rustc)
        .arg("--version")
        .output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .map(|s| s.trim().to_string())
        .unwrap_or_else(|| "unknown".to_string())
}

fn source_revision() -> (String, bool) {
    if let Ok(v) = env::var("HEMOSTAT_SOURCE_REV") {
        if !v.trim().is_empty() {
            return (v.trim().to_string(), false);
        }
    }
    let git = |args: &[&str]| -> Option<String> {
        let out = Command::new("git").args(args).output().ok()?;
        out.status.success().then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
    };
    let Some(rev) = git(&["rev-parse", "--short=12", "HEAD"]).filter(|r| !r.is_empty()) else {
        return ("unknown".to_string(), false);
    };

    let dirty = git(&["status", "--porcelain", "--untracked-files=no"])
        .is_none_or(|s| !s.trim().is_empty());
    (rev, dirty)
}

fn git_watch_paths() -> Vec<PathBuf> {
    let mut out = Vec::new();

    let Some(root) = env::var_os("CARGO_MANIFEST_DIR").map(PathBuf::from) else {
        return out;
    };
    let Some(git) = root.ancestors().map(|a| a.join(".git")).find(|p| p.is_dir()) else {
        return out;
    };
    let head = git.join("HEAD");
    if !head.is_file() {
        return out;
    }

    if let Ok(text) = fs::read_to_string(&head) {
        if let Some(r) = text.trim().strip_prefix("ref: ") {
            let refp = git.join(r);
            if refp.is_file() {
                out.push(refp);
            }
        }
    }
    out.push(head);
    out
}
